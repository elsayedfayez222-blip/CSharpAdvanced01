# Numeric Types
# int & float & complex

print(type(5))
print(type(4.88))  # type() بتطبع نوع الداتا تايب
print(type(4j))

# Sequence Types
# String & List & Tuple
print(type("Elsayed"))
print(type([44, 99, "mo"]))
print(
    type((3, 2, 4))
)  # مقدرش تغير أي عنصر جواه ولا تمسحه بـ del (إلا لو هتمسح التوبل كله).

# Dictionary
# dict
print(type({"name": "mohamed", "age": 30}))  # شبه الجيسون كده في جافا اسكريبت

# Boolean
# bool
print(type(True))

# Set Type
# set
print(type({2, 3, 2, 3}))  # بايثون هيطبعها كده:{ 2, 3} (مسح التكرار تلقائياً!)
